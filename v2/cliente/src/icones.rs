//! nada de emoji fazendo papel de ícone (AGENTS.md, seção 9).

use iced::widget::svg;

macro_rules! icones {
    ($($nome:ident => $arquivo:literal),* $(,)?) => {
        $(
            #[allow(dead_code)]
            pub fn $nome() -> svg::Handle {
                svg::Handle::from_memory(include_bytes!(concat!("../assets/icones/", $arquivo, ".svg")).as_slice())
            }
        )*
    };
}

