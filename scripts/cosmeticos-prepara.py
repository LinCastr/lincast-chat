#!/usr/bin/env python3
"""Prepare the profile cosmetics folder for the server.

Reads a source folder (catalogo.json + webp files) and writes an output folder
with only what the server serves: the animated webp of each item, a static
thumbnail (`mini/<id>.webp`) and a catalogo.json pointing at both.

Thumbnails: the first frame of a profile effect is usually empty, so effects use
the middle frame; everything else uses the first frame.

Usage: cosmeticos-prepara.py <source> <output>
Then copy <output> to ~/callapp/cosmeticos/ on the server.
"""

import json
import shutil
import sys
from pathlib import Path

from PIL import Image

# Older entries have "tipo"; newer ones only say it by folder.
TIPO_DA_PASTA = {"decoracoes-avatar": "decoracao_avatar", "placas-identificacao": "placa_identificacao",
                 "efeitos-perfil": "efeito_perfil", "molduras-perfil": "moldura_perfil"}

MINI_LADO = {"decoracao_avatar": 160, "placa_identificacao": 448,
             "efeito_perfil": 300, "moldura_perfil": 420}


def miniatura(origem: Path, destino: Path, tipo: str) -> None:
    im = Image.open(origem)
    n = getattr(im, "n_frames", 1)
    im.seek(n // 2 if tipo == "efeito_perfil" else 0)
    quadro = im.convert("RGBA")
    lado = MINI_LADO.get(tipo, 300)
    w, h = quadro.size
    if max(w, h) > lado:
        k = lado / max(w, h)
        quadro = quadro.resize((max(1, round(w * k)), max(1, round(h * k))), Image.LANCZOS)
    destino.parent.mkdir(parents=True, exist_ok=True)
    quadro.save(destino, "WEBP", quality=85)


def prepara_moldura(origem: Path, destino: Path) -> str:
    """Say how the frame is placed and prepare the file. "inteira" (a layer
    for the whole card): copied as it is. "topo" (a band that sits on top
    of the card, above its top edge): transparent margins cut, so the band
    starts and ends where the art does; the side margins only when they are
    thin (a narrow ornament in the middle stays narrow)."""
    destino.parent.mkdir(parents=True, exist_ok=True)
    im = Image.open(origem)
    w, h = im.size
    if h / w > 0.9:
        if not destino.exists() or destino.stat().st_mtime != origem.stat().st_mtime:
            shutil.copy2(origem, destino)
        return "inteira"
    quadros, duracoes = [], []
    caixa = None
    for k in range(getattr(im, "n_frames", 1)):
        im.seek(k)
        q = im.convert("RGBA")
        quadros.append(q)
        duracoes.append(im.info.get("duration", 83))
        b = q.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
        if b:
            caixa = b if caixa is None else (min(caixa[0], b[0]), min(caixa[1], b[1]),
                                             max(caixa[2], b[2]), max(caixa[3], b[3]))
    caixa = caixa or (0, 0, w, h)
    lado = min(caixa[0], w - caixa[2])
    x0, x1 = (lado, w - lado) if lado < w * 0.08 else (0, w)
    quadros = [q.crop((x0, caixa[1], x1, caixa[3])) for q in quadros]
    quadros[0].save(destino, "WEBP", quality=90, save_all=len(quadros) > 1,
                    append_images=quadros[1:], duration=duracoes, loop=0)
    return "topo"


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    origem, saida = Path(sys.argv[1]), Path(sys.argv[2])
    itens = json.loads((origem / "catalogo.json").read_text(encoding="utf-8"))
    # Short display names kept apart from catalogo.json (it is regenerated by
    # the art tool); the long text becomes the description.
    curtos_arq = origem / "nomes-curtos.json"
    curtos = json.loads(curtos_arq.read_text(encoding="utf-8")) if curtos_arq.is_file() else {}
    vistos = set()
    novos = []
    for it in itens:
        if not isinstance(it, dict) or it.get("id") in vistos:
            continue
        webp = it.get("arquivo_webp")
        if not webp or not (origem / webp).is_file():
            print(f"sem arquivo: {it.get('id')}", file=sys.stderr)
            continue
        vistos.add(it["id"])
        tipo = it.get("tipo") or TIPO_DA_PASTA.get(it.get("subfolder") or webp.split("/")[0], "")
        destino = saida / webp
        destino.parent.mkdir(parents=True, exist_ok=True)
        ancora = None
        if tipo == "moldura_perfil":
            ancora = prepara_moldura(origem / webp, destino)
        elif not destino.exists() or destino.stat().st_mtime != (origem / webp).stat().st_mtime:
            shutil.copy2(origem / webp, destino)
        mini = f"mini/{it['id']}.webp"
        if not (saida / mini).exists() or (saida / mini).stat().st_mtime < (origem / webp).stat().st_mtime:
            miniatura(destino if ancora else origem / webp, saida / mini, tipo)
        novo = {k: v for k, v in it.items()
                if k not in ("url", "arquivo_raw", "arquivo_previa", "sku", "layer_id", "subfolder")}
        novo["tipo"] = tipo
        curto = curtos.get(it["id"])
        if curto and curto != it.get("nome"):
            novo["descricao"] = it.get("nome", "")
            novo["nome"] = curto
        novo["arquivo_mini"] = mini
        if ancora:
            novo["ancora"] = ancora
        novos.append(novo)
    (saida / "catalogo.json").write_text(json.dumps(novos, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(novos)} itens em {saida}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
